"""Build the assets from source, by script. Runs in hython, the judge's way:

    uv run python probes/hython.py houdini/build/build_hdas.py --out houdini/otls

What it builds (docs/BLUEPRINT.md, section 5): one asset whose operator name is
<hda_namespace>::<hda_flow>::1.0, both read from [tool.cvcops.names] in pyproject.toml (decision 0002). Inside
(flow_network.py): the prep kernel (luminance, gain, gamma), Resample (Box) at the analysis scale, ROP Image writing
analysis.####.exr raw, File COP reading flow.####.exr (Raw, 32-bit, Missing Data on Report Message), and the one
conversion node, which outputs flow as a UV layer and valid as Mono. The Bake and Check Cache buttons call a short
PythonModule that imports cvcops_houdini.bake when pressed. Never hand-edit the built file; change this script and
build again. An Indie session builds a limited-commercial asset (FACTS P7), which is why the asset is built here and
not shipped.

The asset's inputs, outputs, folders and parameters come from controls.json beside this file and from nowhere
else (docs/CONTROLS.md). Only entries whose status is "v0.1" are built; menus marked choices_from read the contract
at build time. Exit 0 built, 1 build error, 3 without hou or a licence, or when the target cannot be replaced.
"""
import argparse
import ast
import json
import os
import shutil
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))


def names():
    with open(ROOT / "pyproject.toml", "rb") as f:
        return tomllib.load(f)["tool"]["cvcops"]["names"]


def controls(status="v0.1"):
    """The asset's interface from controls.json, keeping only entries with the given status."""
    spec = json.loads((Path(__file__).with_name("controls.json")).read_text(encoding="utf-8"))
    for key in ("inputs", "outputs", "controls"):
        spec[key] = [c for c in spec[key] if c.get("status") == status]
    return spec


def contract_tuples():
    """RECIPES and BACKENDS read from src/cvcops/contract.py without importing it (hython never imports cvcops)."""
    tree = ast.parse((ROOT / "src" / "cvcops" / "contract.py").read_text(encoding="utf-8"))
    found = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ("RECIPES", "BACKENDS"):
                found[f"contract.{node.targets[0].id}"] = tuple(ast.literal_eval(node.value))
    return found


def type_name(n):
    return f"{n['hda_namespace']}::{n['hda_flow']}::1.0"


def file_name(n):
    return f"{n['hda_namespace']}_{n['hda_flow']}.hda"


PYTHON_MODULE = '''"""{type_name} button callbacks. Generated by houdini/build/build_hdas.py; change that script, not this."""
ENV_PREFIX = {prefix!r}


def on_bake(node):
    from cvcops_houdini import bake
    return bake.on_bake(node, ENV_PREFIX)


def on_check_cache(node):
    from cvcops_houdini import bake
    return bake.on_check_cache(node, ENV_PREFIX)
'''

STATUS_TEXT = "`pythonexprs(\"hou.pwd().userData('cvcops_{name}') or 'not checked yet'\")`"


def parm_template(hou, c, menus):
    """One hou.ParmTemplate from a controls.json entry."""
    name, label, typ = c["name"], c["label"], c["type"]
    base1 = hou.parmNamingScheme.Base1
    if typ == "float3":
        t = hou.FloatParmTemplate(name, label, 3, default_value=tuple(c["default"]), naming_scheme=base1)
    elif typ == "float":
        lo, hi = c.get("soft_range", (0.0, 10.0))
        t = hou.FloatParmTemplate(name, label, 1, default_value=(c["default"],), min=lo, max=hi)
    elif typ == "menu":
        items = list(c.get("choices") or menus[c["choices_from"]])
        t = hou.MenuParmTemplate(name, label, items, menu_labels=items, default_value=items.index(c["default"]))
    elif typ == "int2":
        t = hou.IntParmTemplate(name, label, 2, default_expression=tuple(c["default"]),
                                default_expression_language=(hou.scriptLanguage.Hscript,) * 2, naming_scheme=base1)
    elif typ == "directory":
        t = hou.StringParmTemplate(name, label, 1, default_value=(c["default"],),
                                   string_type=hou.stringParmType.FileReference, file_type=hou.fileType.Directory)
    elif typ == "button":
        callback = {"bake": "on_bake", "verify": "on_check_cache"}[name]
        t = hou.ButtonParmTemplate(name, label, script_callback=f'hou.phm().{callback}(kwargs["node"])',
                                   script_callback_language=hou.scriptLanguage.Python)
    elif typ == "label":
        t = hou.LabelParmTemplate(name, label, column_labels=(STATUS_TEXT.format(name=name),))
    else:
        raise ValueError(f"controls.json: {name} has type {typ}, which the builder does not build")
    t.setHelp(c["help"])
    return t


def parm_group(hou, subnet, spec):
    """The subnet's own port multiparms kept but hidden, then one tab per controls.json folder."""
    group = subnet.parmTemplateGroup()
    for name in ("inputs", "outputs", "cablerenamebylabel"):
        t = group.find(name)
        if t is not None:
            t.hide(True)
            group.replace(name, t)
    menus = contract_tuples()
    for folder in spec["folders"]:
        entries = [parm_template(hou, c, menus) for c in spec["controls"] if c["folder"] == folder]
        if entries:
            group.append(hou.FolderParmTemplate(f"tab_{folder.lower()}", folder, entries, folder_type=hou.folderType.Tabs))
    return group


def build(hou, out_dir):
    import flow_network
    import stamp as stamp_mod
    n = names()
    spec = controls()
    out_dir = Path(out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    work = out_dir / ".build_tmp"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir()
    target = out_dir / file_name(n)
    tname = type_name(n)
    for path in (target, work / file_name(n)):
        try:
            hou.hda.uninstallFile(path.as_posix())
        except hou.OperationFailed:
            pass

    net = hou.node("/obj").createNode("copnet", "cvcops_build")
    subnet = net.createNode("subnet", n["hda_flow"])
    flow_network.set_ports(subnet, spec)
    subnet.setParmTemplateGroup(parm_group(hou, subnet, spec))
    flow_network.build(subnet)

    tmp = (work / file_name(n)).as_posix()
    kwargs = dict(name=tname, hda_file_name=tmp, description="CVCOPs Flow",
                  min_num_inputs=1, max_num_inputs=1)
    try:
        asset = subnet.createDigitalAsset(create_backup=False, **kwargs)
    except TypeError:
        asset = subnet.createDigitalAsset(**kwargs)
    definition = asset.type().definition()
    definition.setParmTemplateGroup(asset.parmTemplateGroup())
    definition.addSection("PythonModule", PYTHON_MODULE.format(type_name=tname, prefix=n["env_prefix"]))
    definition.setExtraFileOption("PythonModule/IsPython", True)
    build_stamp = {"stamp": stamp_mod.stamp(ROOT), "type": tname, "houdini": hou.applicationVersionString(),
                   "licence": str(hou.licenseCategory())}
    definition.addSection("CvcopsStamp", json.dumps(build_stamp, indent=1))
    definition.updateFromNode(asset)
    definition.save(tmp, template_node=asset)
    hou.hda.uninstallFile(tmp)
    try:
        os.replace(tmp, target)
    except PermissionError as e:
        raise PermissionError(f"cannot replace {target}: a Houdini session may hold it ({e})")
    (out_dir / (file_name(n) + ".stamp.json")).write_text(json.dumps(build_stamp, indent=1) + "\n", encoding="utf-8")
    shutil.rmtree(work, ignore_errors=True)
    with open(target, "rb") as f:
        contents = f.read()
    markers = {m: (m.encode() in contents) for m in ("HouLC", "LIMITED_COMMERCIAL_FILE", "HouNC")}
    return {"type": tname, "file": target.as_posix(), **build_stamp, "markers": markers}


def main(argv=None):
    try:
        import hou
    except ImportError:
        print("build_hdas.py: no hou; run it through probes/hython.py", file=sys.stderr)
        return 3
    ap = argparse.ArgumentParser(description="Build the CVCOPs assets from controls.json.")
    ap.add_argument("--out", default=str(ROOT / "houdini" / "otls"))
    args = ap.parse_args(argv)
    try:
        report = build(hou, args.out)
    except PermissionError as e:
        print(f"build_hdas.py: {e}", file=sys.stderr)
        return 3
    except hou.Error as e:
        print(f"build_hdas.py: build failed: {e}", file=sys.stderr)
        return 1
    print(json.dumps(report, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
